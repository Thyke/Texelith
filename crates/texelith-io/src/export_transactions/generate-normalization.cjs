// Original table generator. Queries the locally installed ICU through Node;
// no downloads, crate dependencies, or third-party implementation code.
// Run from any directory: node path/to/generate-normalization.cjs
const fs = require('node:fs');
const path = require('node:path');
if (process.versions.unicode !== '17.0') throw new Error('Requires Unicode 17.0 ICU data');

const scalars = s => Array.from(s, c => c.codePointAt(0));
const decompositions = [];
const compositions = [];
const marks = [];
const fixtures = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    const ch = String.fromCodePoint(cp);
    const nfd = ch.normalize('NFD');
    // Hangul decomposition/composition is implemented arithmetically.
    if (cp >= 0xac00 && cp <= 0xd7a3) {
        fixtures.push([nfd, ch]);
        continue;
    }
    if (ch !== nfd) {
        decompositions.push([cp, scalars(nfd)]);
        fixtures.push([ch, ch.normalize('NFC')], [nfd, nfd.normalize('NFC')]);
        const parts = Array.from(nfd);
        const last = parts.pop();
        const prefix = parts.join('').normalize('NFC');
        if (last && Array.from(prefix).length === 1 && (prefix + last).normalize('NFC') === ch) {
            compositions.push([prefix.codePointAt(0), last.codePointAt(0), cp]);
        }
    } else if (('\u0345' + ch + '\u0334').normalize('NFD').endsWith('\u0345')) {
        // Nonzero combining classes reorder across these class-240/class-1
        // sentinels. Starters block reordering. Only relative class order is
        // needed by canonical ordering and composition blocking.
        marks.push(ch);
    }
}
function compare(a, b) {
    if (a === b) return 0;
    if ((a + b).normalize('NFD') === b + a) return 1;
    if ((b + a).normalize('NFD') === a + b) return -1;
    return 0;
}
marks.sort(compare);
let rank = 0;
let previous;
const classes = marks.map(ch => {
    if (!previous || compare(previous, ch) !== 0) rank++;
    previous = ch;
    return [ch.codePointAt(0), rank];
}).sort((a, b) => a[0] - b[0]);
compositions.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
const hex = cp => '0x' + cp.toString(16);
const lines = [
    '// Generated by generate-normalization.cjs from Unicode 17.0 / ICU ' + process.versions.icu + '.',
    '// Unicode data license: LICENSE-UNICODE. No external implementation code.',
    '// CLASSES contains ordinal ranks, not the numeric Unicode CCC values.',
    'pub(super) const DECOMPOSITIONS: &[(u32, &[u32])] = &[',
    ...decompositions.map(([cp, parts]) => `    (${hex(cp)}, &[${parts.map(hex).join(', ')}]),`),
    '];',
    'pub(super) const CLASSES: &[(u32, u8)] = &[',
    ...classes.map(([cp, cc]) => `    (${hex(cp)}, ${cc}),`),
    '];',
    'pub(super) const COMPOSITIONS: &[((u32, u32), u32)] = &[',
    ...compositions.map(([a, b, cp]) => `    ((${hex(a)}, ${hex(b)}), ${hex(cp)}),`),
    '];',
    '',
];
fs.writeFileSync(path.join(__dirname, 'normalization_tables.rs'), lines.join('\n'));
// Deterministic mixed-script sequences exercise reordering, equal-class
// blocking, leading marks and starters independently of the Rust algorithm.
let seed = 77;
const pick = n => { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed % n; };
const bases = ['A', 'e', '\u212b', '\uac00', '\u1100', '\u0915', '\u09c7', '\u1e0a'];
for (let i = 0; i < 8192; i++) {
    let input = i % 2 ? bases[pick(bases.length)] : '';
    for (let j = 0; j < 5; j++) input += marks[pick(marks.length)];
    input += bases[pick(bases.length)];
    fixtures.push([input, input.normalize('NFC')]);
}
const fixtureDir = path.resolve(__dirname, '../../tests/mvp_t077');
fs.mkdirSync(fixtureDir, { recursive: true });
fs.writeFileSync(path.join(fixtureDir, 'nfc.json'), JSON.stringify(fixtures) + '\n');
console.log(JSON.stringify({ unicode: process.versions.unicode, icu: process.versions.icu,
    decompositions: decompositions.length, compositions: compositions.length,
    combiningScalars: classes.length, classRanks: rank, fixtures: fixtures.length }));
