#!/usr/bin/env python3
"""Regenerate dependency notices from the locked Windows, Linux and macOS graphs."""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = ("x86_64-pc-windows-msvc", "x86_64-unknown-linux-gnu", "aarch64-apple-darwin")
output = ROOT / "THIRD_PARTY_NOTICES.md"
old = output.read_text(encoding="utf-8")
prefix = old.split("## Dependency inventory (Windows graph)")[0].split("## Hack font")[0]
fonts = old.split("## Hack font", 1)[1].split("## Dependency inventory (release targets)")[0]
packages = {}
for target in TARGETS:
    data = json.loads(subprocess.check_output(["cargo", "metadata", "--locked", "--offline", "--format-version", "1", "--filter-platform", target], cwd=ROOT))
    for package in data["packages"]:
        if package["source"]:
            packages[package["id"]] = package

groups = {}
missing = []
for package in packages.values():
    directory = pathlib.Path(package["manifest_path"]).parent
    files = sorted(p for p in directory.iterdir() if p.is_file() and p.name.lower().startswith(("license", "licence", "copying", "notice")))
    if package["license_file"]:
        candidate = directory / package["license_file"]
        if candidate.is_file() and candidate not in files:
            files.append(candidate)
    if not files:
        missing.append(f"{package['name']} {package['version']} ({package['license']})")
    groups.setdefault(package["license"] or "See license file", []).append((package, files))

lines = [prefix, "## Hack font\n", fonts.rstrip(), "\n\n## Dependency inventory (release targets)\n\n", "Generated by `python scripts/generate-third-party-notices.py` from the locked dependency graphs for Windows x86-64, Linux x86-64, and macOS arm64, including build and test dependencies. License expressions describe the alternatives offered by each crate; included texts retain upstream notices.\n"]
for license_name, entries in sorted(groups.items()):
    lines.append(f"\n### {license_name}\n")
    for package, files in sorted(entries, key=lambda x: (x[0]["name"], x[0]["version"])):
        lines.append(f"\n#### {package['name']} {package['version']}\n\nSource: {package['repository'] or 'crates.io'}\n")
        for path in files:
            content = path.read_text(encoding="utf-8", errors="replace").strip()
            lines.append(f"\n{path.name}:\n\n```text\n{content}\n```\n")
if missing:
    print("No packaged license text:", *missing, sep="\n")
    lines.append("\n## Unresolved upstream license texts\n\nThe following crate archives do not contain a root license file. Their upstream copyright and license notices must be checked before release:\n\n")
    lines.extend(f"- {item}\n" for item in sorted(missing))
output.write_text("".join(lines), encoding="utf-8", newline="\n")
if missing:
    sys.exit(1)
